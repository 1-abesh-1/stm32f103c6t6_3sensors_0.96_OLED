/* ----------------------------------------------------------
   Write one character
   ---------------------------------------------------------- */
void OLED_WriteChar(char c)
{
    /*
     * Printable ASCII range:
     * 0x20 = Space
     * 0x7E = ~
     */
    if (c < 0x20 || c > 0x7E)
    {
        return;
    }

    uint8_t index = (uint8_t)c - 0x20;

    /*
     * Move to next line if character
     * would exceed display width.
     */
    if (cursor_x + 6 >= OLED_WIDTH)
    {
        cursor_x = 0;
        cursor_y++;
    }

    /*
     * Wrap vertically.
     */
    if (cursor_y >= 8)
    {
        cursor_y = 0;
    }

    /*
     * Write 5x7 character.
     */
    for (uint8_t i = 0; i < 5; i++)
    {
        OLED_Buffer[
            cursor_y * OLED_WIDTH + cursor_x
        ] = Font5x7[index][i];

        cursor_x++;
    }

    /*
     * One blank column between characters.
     */
    OLED_Buffer[
        cursor_y * OLED_WIDTH + cursor_x
    ] = 0x00;

    cursor_x++;
}


/* ----------------------------------------------------------
   Write string
   ---------------------------------------------------------- */
void OLED_WriteString(const char *str)
{
    while (*str)
    {
        OLED_WriteChar(*str++);
    }
}

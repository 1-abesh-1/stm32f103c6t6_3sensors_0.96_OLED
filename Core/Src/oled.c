#include "oled.h"
#include <string.h>

extern I2C_HandleTypeDef hi2c1;

/*
 * SSD1306 128x64 Display Buffer
 *
 * 128 columns
 * 64 rows
 * 8 pages
 * 1024 bytes total
 */
static uint8_t OLED_Buffer[OLED_WIDTH * OLED_HEIGHT / 8];

static uint8_t cursor_x = 0;
static uint8_t cursor_y = 0;


/* ----------------------------------------------------------
   Send one command
   ---------------------------------------------------------- */
static void OLED_WriteCommand(uint8_t command)
{
    uint8_t data[2];

    data[0] = 0x00;
    data[1] = command;

    HAL_I2C_Master_Transmit(
        &hi2c1,
        OLED_ADDR,
        data,
        2,
        HAL_MAX_DELAY
    );
}


/* ----------------------------------------------------------
   Send data to OLED
   ---------------------------------------------------------- */
static void OLED_WriteData(uint8_t *data, uint16_t size)
{
    uint8_t buffer[129];

    buffer[0] = 0x40;

    while (size > 0)
    {
        uint16_t chunk;

        if (size > 128)
            chunk = 128;
        else
            chunk = size;

        memcpy(&buffer[1], data, chunk);

        HAL_I2C_Master_Transmit(
            &hi2c1,
            OLED_ADDR,
            buffer,
            chunk + 1,
            HAL_MAX_DELAY
        );

        data += chunk;
        size -= chunk;
    }
}


/* ----------------------------------------------------------
   Initialize SSD1306
   ---------------------------------------------------------- */
void OLED_Init(void)
{
    HAL_Delay(100);

    OLED_WriteCommand(0xAE);    // Display OFF

    OLED_WriteCommand(0x20);    // Memory addressing mode
    OLED_WriteCommand(0x00);    // Horizontal addressing mode

    OLED_WriteCommand(0xB0);    // Page start address

    OLED_WriteCommand(0xC8);    // COM scan direction

    OLED_WriteCommand(0x00);    // Low column address
    OLED_WriteCommand(0x10);    // High column address

    OLED_WriteCommand(0x40);    // Start line address

    OLED_WriteCommand(0x81);    // Contrast
    OLED_WriteCommand(0x7F);

    OLED_WriteCommand(0xA1);    // Segment remap

    OLED_WriteCommand(0xA6);    // Normal display

    OLED_WriteCommand(0xA8);    // Multiplex ratio
    OLED_WriteCommand(0x3F);

    OLED_WriteCommand(0xA4);    // Display follows RAM

    OLED_WriteCommand(0xD3);    // Display offset
    OLED_WriteCommand(0x00);

    OLED_WriteCommand(0xD5);    // Display clock
    OLED_WriteCommand(0x80);

    OLED_WriteCommand(0xD9);    // Pre-charge
    OLED_WriteCommand(0xF1);

    OLED_WriteCommand(0xDA);    // COM pins configuration
    OLED_WriteCommand(0x12);

    OLED_WriteCommand(0xDB);    // VCOMH
    OLED_WriteCommand(0x40);

    OLED_WriteCommand(0x8D);    // Charge pump
    OLED_WriteCommand(0x14);

    OLED_WriteCommand(0xAF);    // Display ON

    OLED_Clear();
    OLED_Update();
}


/* ----------------------------------------------------------
   Clear display buffer
   ---------------------------------------------------------- */
void OLED_Clear(void)
{
    memset(OLED_Buffer, 0, sizeof(OLED_Buffer));

    cursor_x = 0;
    cursor_y = 0;
}


/* ----------------------------------------------------------
   Send buffer to OLED
   ---------------------------------------------------------- */
void OLED_Update(void)
{
    for (uint8_t page = 0; page < 8; page++)
    {
        OLED_WriteCommand(0xB0 + page);

        OLED_WriteCommand(0x00);
        OLED_WriteCommand(0x10);

        OLED_WriteData(
            &OLED_Buffer[OLED_WIDTH * page],
            OLED_WIDTH
        );
    }
}


/* ----------------------------------------------------------
   Set cursor
   ---------------------------------------------------------- */
void OLED_SetCursor(uint8_t x, uint8_t y)
{
    cursor_x = x;
    cursor_y = y;
}


